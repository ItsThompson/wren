import { readFile, writeFile } from 'node:fs/promises'

const inputPath = new URL('../openapi.json', import.meta.url)
const outputPath = new URL('../src/api/operationRegistry.generated.ts', import.meta.url)
const document = JSON.parse(await readFile(inputPath, 'utf8'))
const entries = []
const domainByTag = {
  accounts: 'accounts',
  auth: 'accounts',
  listing: 'accounts',
  onboarding: 'accounts',
  oauth: 'oauth',
  progress: 'progress',
  roadmaps: 'roadmaps',
  skill: 'skill',
}

for (const [path, pathItem] of Object.entries(document.paths ?? {})) {
  for (const [method, operation] of Object.entries(pathItem)) {
    if (!['get', 'post', 'put', 'patch', 'delete', 'options', 'head', 'trace'].includes(method)) continue
    if (!operation.operationId) throw new Error(`Missing operationId for ${method.toUpperCase()} ${path}`)
    const [tag] = operation.tags ?? []
    const domain = domainByTag[tag]
    if (!domain || (operation.tags ?? []).length !== 1) {
      throw new Error(`Missing browser domain for ${method.toUpperCase()} ${path}`)
    }
    entries.push([`${method.toUpperCase()} ${path}`, operation.operationId, domain])
  }
}

entries.sort(([left], [right]) => left.localeCompare(right))
const registry = Object.fromEntries(entries.map(([key, operationId]) => [key, operationId]))
const domains = Object.fromEntries(entries.map(([key, , domain]) => [key, domain]))
const source = `// Generated by scripts/generate-operation-registry.mjs. Do not edit by hand.\n\nexport const operationRegistry = ${JSON.stringify(registry, null, 2)} as const\n\nexport type OperationKey = keyof typeof operationRegistry\nexport type OperationId = (typeof operationRegistry)[OperationKey]\n\nexport const operationDomainRegistry = ${JSON.stringify(domains, null, 2)} as const satisfies Record<OperationKey, string>\n\nexport type OperationDomain = (typeof operationDomainRegistry)[OperationKey]\n`
await writeFile(outputPath, source)
